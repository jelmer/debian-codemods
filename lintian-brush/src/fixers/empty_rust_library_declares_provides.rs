use crate::declare_detector;
use crate::diagnostic::{Action, DebcargoAction, Diagnostic};
use crate::{Certainty, FixerError, FixerPreferences, LintianIssue, Visibility};
use debian_workspace::Workspace;
use std::path::PathBuf;

const COLLAPSE_FEATURES: &str = "collapse_features";

pub fn detect(
    ws: &dyn Workspace,
    _preferences: &FixerPreferences,
) -> Result<Vec<Diagnostic>, FixerError> {
    let debcargo_rel = PathBuf::from("debian/debcargo.toml");

    // The tag can fire on any librust-* package, whether or not it is
    // debcargo-managed, but the only automated remedy we know is to set
    // collapse_features = true in debcargo.toml. Traditional debhelper-style
    // Rust packages need manual restructuring, so skip them here.
    //
    // In a debcargo-managed VCS tree, debian/control is generated by
    // `debcargo package` from debian/debcargo.toml and is typically absent,
    // so we do not consult it: the presence of debcargo.toml alone tells us
    // that debcargo will produce the empty librust-*+feat-dev metapackages
    // this tag flags, unless collapse_features is set.
    let Some(doc) = ws.parsed_debcargo()? else {
        return Ok(Vec::new());
    };

    if doc
        .get(COLLAPSE_FEATURES)
        .and_then(|v| v.as_bool())
        .unwrap_or(false)
    {
        return Ok(Vec::new());
    }

    // collapse_features = true removes the per-feature librust-*+feat-dev
    // subpackages debcargo would otherwise generate. Anything in the archive
    // that depends on one of those exact subpackages breaks, so this can
    // never be Certain from source alone.
    let issue = LintianIssue::source_with_info(
        "empty-rust-library-declares-provides",
        Visibility::Error,
        vec![],
    );
    Ok(vec![Diagnostic::with_actions(
        issue,
        "Set collapse_features = true in debian/debcargo.toml.",
        "Set collapse_features = true in debian/debcargo.toml.",
        vec![Action::Debcargo(DebcargoAction::SetTopLevelBool {
            file: debcargo_rel,
            field: COLLAPSE_FEATURES.to_string(),
            value: true,
        })],
    )
    .with_certainty(Certainty::Possible)])
}

declare_detector! {
    name: "empty-rust-library-declares-provides",
    tags: ["empty-rust-library-declares-provides"],
    triggers: [
        debian_workspace::Trigger::DebcargoField("collapse_features"),
    ],
    detect: |ws, prefs| detect(ws, prefs),
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::detector::Detector;
    use crate::{FixerPreferences, Version};
    use std::fs;
    use std::path::Path;
    use tempfile::TempDir;

    fn run_apply(base: &Path) -> Result<crate::FixerResult, FixerError> {
        run_apply_with(base, &FixerPreferences::default())
    }

    fn run_apply_with(
        base: &Path,
        prefs: &FixerPreferences,
    ) -> Result<crate::FixerResult, FixerError> {
        let version: Version = "0.1.0-1".parse().unwrap();
        let adapter = DetectorImpl;
        let ws = debian_workspace::fs_workspace::FsWorkspace::new(
            base,
            Some("rust-example".into()),
            Some(version),
        );
        adapter.apply(&ws, prefs)
    }

    fn write_debcargo(tmp: &Path, contents: &str) {
        let debian = tmp.join("debian");
        fs::create_dir_all(&debian).unwrap();
        fs::write(debian.join("debcargo.toml"), contents).unwrap();
    }

    #[test]
    fn test_adds_collapse_features_when_missing() {
        let tmp = TempDir::new().unwrap();
        write_debcargo(tmp.path(), "[source]\nsection = \"rust\"\n");

        let result = run_apply(tmp.path()).unwrap();
        assert_eq!(
            result.description,
            "Set collapse_features = true in debian/debcargo.toml."
        );
        assert_eq!(result.fixed_lintian_issues.len(), 1);
        assert_eq!(result.certainty, Some(Certainty::Possible));
        // Bare top-level keys must precede any table; toml_edit reorders
        // the new key so [source] stays a table header.
        assert_eq!(
            fs::read_to_string(tmp.path().join("debian/debcargo.toml")).unwrap(),
            "collapse_features = true\n[source]\nsection = \"rust\"\n",
        );
    }

    #[test]
    fn test_no_change_when_collapse_features_already_true() {
        let tmp = TempDir::new().unwrap();
        write_debcargo(tmp.path(), "collapse_features = true\n");
        assert!(matches!(run_apply(tmp.path()), Err(FixerError::NoChanges)));
    }

    #[test]
    fn test_no_change_without_debcargo_toml() {
        let tmp = TempDir::new().unwrap();
        fs::create_dir_all(tmp.path().join("debian")).unwrap();
        assert!(matches!(run_apply(tmp.path()), Err(FixerError::NoChanges)));
    }

    #[test]
    fn test_overwrites_explicit_false() {
        let tmp = TempDir::new().unwrap();
        write_debcargo(tmp.path(), "collapse_features = false\n");
        let result = run_apply(tmp.path()).unwrap();
        assert_eq!(result.fixed_lintian_issues.len(), 1);
        assert_eq!(
            fs::read_to_string(tmp.path().join("debian/debcargo.toml")).unwrap(),
            "collapse_features = true\n",
        );
    }

    #[test]
    fn test_skipped_when_minimum_certainty_certain() {
        let tmp = TempDir::new().unwrap();
        write_debcargo(tmp.path(), "[source]\nsection = \"rust\"\n");
        let prefs = FixerPreferences {
            minimum_certainty: Some(Certainty::Certain),
            ..Default::default()
        };
        assert!(matches!(
            run_apply_with(tmp.path(), &prefs),
            Err(FixerError::NotCertainEnough(..))
        ));
    }

    #[test]
    fn test_applied_when_minimum_certainty_possible() {
        let tmp = TempDir::new().unwrap();
        write_debcargo(tmp.path(), "[source]\nsection = \"rust\"\n");
        let prefs = FixerPreferences {
            minimum_certainty: Some(Certainty::Possible),
            ..Default::default()
        };
        let result = run_apply_with(tmp.path(), &prefs).unwrap();
        assert_eq!(result.fixed_lintian_issues.len(), 1);
    }

    #[test]
    fn test_does_not_care_about_debian_control() {
        // Debcargo VCS trees do not commit debian/control. The fixer must
        // decide from debian/debcargo.toml alone and ignore whatever
        // debian/control looks like when it happens to be present.
        let tmp = TempDir::new().unwrap();
        write_debcargo(tmp.path(), "[source]\nsection = \"rust\"\n");
        fs::write(
            tmp.path().join("debian/control"),
            "Source: not-a-rust-package\nMaintainer: A <a@b>\n\n\
             Package: libfoo-dev\nArchitecture: any\nDescription: unrelated\n",
        )
        .unwrap();
        let result = run_apply(tmp.path()).unwrap();
        assert_eq!(result.fixed_lintian_issues.len(), 1);
    }
}
